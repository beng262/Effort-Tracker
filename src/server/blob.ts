import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { BlobServiceClient } from '@azure/storage-blob';
import { config } from './config.js';

export interface BlobStore {
  put(path: string, data: Buffer): Promise<void>;
  get(path: string): Promise<Buffer>;
}

export function createBlobStore(): BlobStore {
  if (config.AZURE_STORAGE_CONNECTION_STRING) {
    const container = BlobServiceClient.fromConnectionString(config.AZURE_STORAGE_CONNECTION_STRING).getContainerClient(config.BLOB_CONTAINER);
    let ready: Promise<unknown> | null = null;
    const ensure = () => (ready ??= container.createIfNotExists());
    return {
      async put(path, data) { await ensure(); await container.getBlockBlobClient(path).uploadData(data); },
      async get(path) { await ensure(); return container.getBlockBlobClient(path).downloadToBuffer(); },
    };
  }
  // Local development: files on disk. The path is always generated by the server, never taken from a client.
  const root = resolve(config.LOCAL_UPLOAD_DIR);
  const safe = (p: string) => {
    const full = resolve(join(root, p));
    if (!full.startsWith(root)) throw new Error('Bad blob path');
    return full;
  };
  return {
    async put(path, data) { const f = safe(path); await mkdir(dirname(f), { recursive: true }); await writeFile(f, data); },
    async get(path) { return readFile(safe(path)); },
  };
}
